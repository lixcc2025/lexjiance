"""引擎测试：用 ffmpeg 现场生成几个样本（干净的、时间戳断档、多一个关键帧、带 AI 标识、带 AI 工具名），
看检测结果对不对。跑法：cd engine && python -m unittest -v
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from avengine.pipeline import analyze  # noqa: E402
from avengine.models import AI, EDIT  # noqa: E402

FF = shutil.which("ffmpeg")
X264 = ["-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p", "-x264-params", "keyint=30:min-keyint=30:scenecut=0"]


def ff(*args):
    subprocess.run([FF, "-v", "error", "-y", *args], check=True)


@unittest.skipIf(not FF, "没有 ffmpeg")
class EngineTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.dir = tempfile.mkdtemp(prefix="avengine-test-")
        d = cls.dir
        src = ["-f", "lavfi", "-i", "testsrc=size=320x240:rate=30", "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=16000"]
        ff(*src, "-t", "6", *X264, "-c:a", "aac", os.path.join(d, "clean.mp4"))
        # 第 3 秒后时间戳整体后移 2 秒（模拟删掉一段后直接拼接）
        ff("-f", "lavfi", "-i", "testsrc=size=320x240:rate=30", "-t", "6", "-vf", "setpts='if(gte(N,90),PTS+2/TB,PTS)'",
           "-fps_mode", "passthrough", *X264, os.path.join(d, "gap.mp4"))
        # 固定 1 秒一个关键帧，2.5 秒处强制多插一个
        ff(*src[:4], "-t", "6", "-force_key_frames", "2.5", *X264, os.path.join(d, "extra_key.mp4"))
        aigc = json.dumps({"Label": "1", "ContentProducer": "测试生成服务", "ProduceID": "abc123"}, ensure_ascii=False)
        ff("-f", "lavfi", "-i", "sine=frequency=440:sample_rate=16000", "-t", "3", "-metadata", f"AIGC={aigc}",
           os.path.join(d, "aigc.mp3"))
        ff(*src, "-t", "3", *X264, "-c:a", "aac", "-metadata", "comment=Generated by Kling AI", os.path.join(d, "kling.mp4"))
        ff("-f", "lavfi", "-i", "sine=frequency=440:sample_rate=16000", "-t", "3", os.path.join(d, "voice.wav"))

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls.dir, ignore_errors=True)

    def run_on(self, name):
        events = []
        r = analyze(os.path.join(self.dir, name), emit=lambda k, p: events.append(k))
        return r, events

    def test_clean_video(self):
        r, events = self.run_on("clean.mp4")
        bad = [f for f in r.findings if f.severity != "info"]
        self.assertEqual(bad, [], [f.title for f in bad])
        self.assertEqual(r.edit.level, "none")
        self.assertEqual(r.ai.level, "unknown")   # AI 模型（云端）没跑，不能说「没有 AI」
        self.assertIn("progress", events)
        self.assertIn("finding", events)
        names = {s.name: s for s in r.detectors}
        self.assertTrue(names["metadata"].ok and not names["metadata"].skipped)
        self.assertEqual(set(names), {"metadata", "structure", "audio_splice"})

    def test_timestamp_gap(self):
        r, _ = self.run_on("gap.mp4")
        gaps = [f for f in r.findings if f.category == EDIT and "时间戳" in f.title]
        self.assertEqual(len(gaps), 1, [f.title for f in r.findings])
        self.assertAlmostEqual(gaps[0].start, 2.967, delta=0.05)
        self.assertAlmostEqual(gaps[0].end, 5.0, delta=0.05)
        self.assertEqual(r.edit.level, "suspicious")
        # 纯视频文件：声音相关检测项跳过
        self.assertEqual({s.name: s.skipped for s in r.detectors}["audio_splice"], "没有音频")

    def test_extra_keyframe(self):
        r, _ = self.run_on("extra_key.mp4")
        kf = [f for f in r.findings if "关键帧" in f.title]
        self.assertEqual(len(kf), 1, [f.title for f in r.findings])
        self.assertAlmostEqual(kf[0].start, 2.5, delta=0.05)

    def test_aigc_label(self):
        r, _ = self.run_on("aigc.mp3")
        hit = [f for f in r.findings if f.category == AI and "隐式标识" in f.title]
        self.assertEqual(len(hit), 1, [f.title for f in r.findings])
        self.assertEqual(hit[0].evidence["生成合成服务提供者"], "测试生成服务")
        self.assertEqual(hit[0].evidence["内容制作编号"], "abc123")
        self.assertEqual(r.ai.level, "likely")

    def test_ai_tool_name(self):
        r, _ = self.run_on("kling.mp4")
        hit = [f for f in r.findings if f.category == AI and "可灵" in f.title]
        self.assertEqual(len(hit), 1, [f.title for f in r.findings])
        self.assertEqual(r.ai.level, "likely")

    def test_audio_only(self):
        r, _ = self.run_on("voice.wav")
        sk = {s.name: s.skipped for s in r.detectors}
        self.assertEqual(sk["structure"], "")
        self.assertEqual(sk["audio_splice"], "")
        self.assertEqual(r.media["video"], None)

    def test_cli_jsonl(self):
        out = subprocess.run([sys.executable, "-m", "avengine", "analyze", os.path.join(self.dir, "gap.mp4"), "--jsonl"],
                             cwd=os.path.join(os.path.dirname(__file__), ".."), capture_output=True, check=True)
        lines = [json.loads(x) for x in out.stdout.decode("utf-8").splitlines()]
        self.assertEqual(lines[-1]["type"], "result")
        self.assertEqual(lines[-1]["edit"]["level"], "suspicious")
        self.assertTrue(any(x["type"] == "progress" for x in lines))

    def test_preview(self):
        from avengine.preview import make_preview
        out = os.path.join(self.dir, "pv")
        r = make_preview(os.path.join(self.dir, "clean.mp4"), out)
        self.assertAlmostEqual(r["duration"], 6.0, delta=0.1)
        self.assertGreater(len(r["waveform"]), 1000)
        self.assertTrue(all(0 <= v <= 1 for v in r["waveform"]))
        self.assertTrue(r["spectrogram"] and os.path.isfile(r["spectrogram"]))
        self.assertEqual(len(r["frames"]), 24)
        self.assertTrue(all(os.path.isfile(f["path"]) for f in r["frames"]))
        a = make_preview(os.path.join(self.dir, "voice.wav"), os.path.join(self.dir, "pv2"))
        self.assertEqual(a["frames"], [])
        self.assertTrue(a["waveform"] and a["spectrogram"])
        v = make_preview(os.path.join(self.dir, "gap.mp4"), os.path.join(self.dir, "pv3"))   # 没有声音
        self.assertEqual(v["waveform"], [])
        self.assertIsNone(v["spectrogram"])

    def test_extract(self):
        from avengine.extract import extract
        r = extract(os.path.join(self.dir, "clean.mp4"), os.path.join(self.dir, "ex"), max_frames=4)
        self.assertTrue(r["audio"] and os.path.isfile(r["audio"]))
        self.assertEqual(r["sample_rate"], 16000)
        self.assertEqual(len(r["frames"]), 4)
        self.assertEqual([round(f["t"], 2) for f in r["frames"]], [0.75, 2.25, 3.75, 5.25])
        a = extract(os.path.join(self.dir, "voice.wav"), os.path.join(self.dir, "ex2"))
        self.assertEqual(a["frames"], [])
        v = extract(os.path.join(self.dir, "gap.mp4"), os.path.join(self.dir, "ex3"), max_frames=3)
        self.assertIsNone(v["audio"])

    def test_bad_file(self):
        p = os.path.join(self.dir, "not_media.mp4")
        with open(p, "w") as f:
            f.write("hello")
        out = subprocess.run([sys.executable, "-m", "avengine", "analyze", p, "--jsonl"],
                             cwd=os.path.join(os.path.dirname(__file__), ".."), capture_output=True)
        self.assertEqual(out.returncode, 2)
        self.assertEqual(json.loads(out.stdout.decode("utf-8").splitlines()[-1])["type"], "error")


if __name__ == "__main__":
    unittest.main()
